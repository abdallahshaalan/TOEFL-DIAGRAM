/**
 * Generates src/data/toeflVocabulary.js from curated tuple lists.
 * Run: node scripts/generate-toefl-vocab.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { ALL_TUPLES } from "./vocab/all-tuples.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, "..", "src", "data", "toeflVocabulary.js");

const TOEFL_CATEGORIES = [
  "academic-vocabulary",
  "high-frequency-academic",
  "reading-vocabulary",
  "listening-vocabulary",
  "speaking-vocabulary",
  "writing-vocabulary",
  "academic-verbs",
  "academic-adjectives",
  "academic-nouns",
  "academic-connectors",
  "advanced-vocabulary",
  "word-families",
];

function slug(word) {
  return String(word)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "");
}

const DEFAULT_CATEGORIES = {
  verb: ["academic-vocabulary", "academic-verbs", "high-frequency-academic"],
  noun: ["academic-vocabulary", "academic-nouns", "reading-vocabulary"],
  adjective: ["academic-vocabulary", "academic-adjectives", "writing-vocabulary"],
  adverb: ["academic-vocabulary", "writing-vocabulary"],
  connector: ["academic-vocabulary", "academic-connectors", "writing-vocabulary"],
};

const DEFAULT_SKILLS = {
  verb: ["reading", "writing", "speaking"],
  noun: ["reading", "listening", "writing"],
  adjective: ["reading", "writing"],
  adverb: ["writing", "speaking"],
  connector: ["writing", "reading", "speaking"],
};

function expandTuple(t) {
  const [
    word,
    pos,
    difficulty,
    definitionEn,
    translationAr,
    explanationEn,
    exampleEn,
    exampleAr,
    synonyms = [],
    antonyms = [],
    wordFamily = [],
    collocations = [],
    categories,
    skills,
    phonetic = null,
    provenance = "academic-core",
  ] = t;

  const cats = categories ?? DEFAULT_CATEGORIES[pos] ?? ["academic-vocabulary"];
  const sk = skills ?? DEFAULT_SKILLS[pos] ?? ["reading", "writing"];

  return {
    id: `toefl_${slug(word)}`,
    library: "toefl",
    word,
    pos,
    definitionEn,
    translationAr,
    explanationEn,
    exampleEn,
    exampleAr,
    synonyms,
    antonyms,
    wordFamily,
    collocations,
    difficulty,
    categories: cats,
    skills: sk,
    phonetic,
    provenance,
  };
}

function buildVocabulary() {
  const seen = new Set();
  const list = [];
  for (const tuple of ALL_TUPLES) {
    const wordKey = tuple[0].toLowerCase();
    if (seen.has(wordKey)) continue;
    seen.add(wordKey);
    list.push(expandTuple(tuple));
  }
  return list;
}

function serialize(entries) {
  const body = JSON.stringify(entries, null, 2)
    .replace(/"([^"]+)":/g, "$1:");
  return `/** Auto-generated by scripts/generate-toefl-vocab.mjs — do not edit by hand. */\n\nconst toeflVocabulary = ${body};\n\nexport const TOEFL_CATEGORIES = ${JSON.stringify(TOEFL_CATEGORIES, null, 2)};\n\nexport default toeflVocabulary;\n`;
}

const vocab = buildVocabulary();
const ids = vocab.map((e) => e.id);
const uniqueIds = new Set(ids);
const words = vocab.map((e) => e.word.toLowerCase());
const uniqueWords = new Set(words);

if (vocab.length < 450) {
  console.error(`FAIL: only ${vocab.length} entries (need >= 450)`);
  process.exit(1);
}
if (uniqueIds.size !== ids.length) {
  console.error("FAIL: duplicate ids");
  process.exit(1);
}
if (uniqueWords.size !== words.length) {
  console.error("FAIL: duplicate words");
  process.exit(1);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, serialize(vocab), "utf8");
console.log(`Wrote ${vocab.length} entries → ${OUT}`);